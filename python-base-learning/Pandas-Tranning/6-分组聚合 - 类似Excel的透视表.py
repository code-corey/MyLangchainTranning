import pandas as pd

# 创建销售数据
df = pd.DataFrame({
    '区域': ['北区', '南区', '东区', '北区', '南区', '东区', '北区', '南区'],
    '产品': ['手机', '手机', '手机', '电脑', '电脑', '电脑', '平板', '平板'],
    '销售额': [10000, 12000, 9000, 25000, 28000, 22000, 8000, 8500],
    '数量': [10, 12, 9, 5, 6, 4, 8, 9]
})

print("原始销售数据:")
print(df)

# 单列分组：按区域计算总销售额
区域销售 = df.groupby('区域')['销售额'].sum()
print("\n各区域总销售额:")
print(区域销售)

# 多列分组：按区域和产品计算总和
分组汇总 = df.groupby(['区域', '产品'])[['销售额', '数量']].sum()
print("\n各区域各产品的销售汇总:")
print(分组汇总)

# 多种聚合函数
多种统计 = df.groupby('区域')['销售额'].agg(['sum', 'mean', 'max', 'min', 'count'])
print("\n各区域的销售额统计:")
print(多种统计)

# 对不同列使用不同聚合函数
不同聚合 = df.groupby('区域').agg({
    '销售额': ['sum', 'mean'],
    '数量': ['sum', 'count']
})
print("\n各区域的不同统计:")
print(不同聚合)

# 重置索引（把分组键变回列）
重置后 = df.groupby('区域')['销售额'].sum().reset_index()
print("\n重置索引后:")
print(重置后)