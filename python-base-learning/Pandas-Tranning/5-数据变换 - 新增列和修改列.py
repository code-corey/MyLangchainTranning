import pandas as pd

# 创建销售数据
df = pd.DataFrame({
    '产品': ['苹果', '香蕉', '橙子', '葡萄', '西瓜'],
    '销量': [100, 150, 80, 120, 60],
    '单价': [5, 3, 4, 8, 2],
    '日期': ['2024-01-01', '2024-01-02', '2024-01-03', '2024-01-04', '2024-01-05']
})

print("原始数据:")
print(df)

# 新增列：计算总销售额
df['总销售额'] = df['销量'] * df['单价']
print("\n新增总销售额列:")
print(df)

# 新增列：基于条件的分类
df['销售等级'] = df['销量'].apply(lambda x: '高' if x > 100 else ('中' if x > 80 else '低'))
print("\n添加销售等级:")
print(df)

# 使用map进行映射
等级映射 = {'高': 'A级', '中': 'B级', '低': 'C级'}
df['等级代码'] = df['销售等级'].map(等级映射)
print("\n添加等级代码:")
print(df)

# 修改数据类型
df['日期'] = pd.to_datetime(df['日期'])  # 转为日期类型
print(f"\n日期列的类型: {df['日期'].dtype}")

# 提取日期信息
df['星期几'] = df['日期'].dt.dayofweek  # 0=周一, 6=周日
df['月份'] = df['日期'].dt.month
print("\n添加日期特征:")
print(df[['产品', '日期', '星期几', '月份']])