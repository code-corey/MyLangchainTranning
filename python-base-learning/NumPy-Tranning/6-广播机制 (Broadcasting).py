import numpy as np

# 矩阵 (3x4) 与向量 (4,) 相加
mat = np.arange(12).reshape(3, 4)   # 3行4列
vec = np.array([100, 200, 300, 400]) # 长度为4

result = mat + vec
print("矩阵:\n", mat)
print("向量:", vec)
print("广播相加结果:\n", result)

"""
result = mat + vec 中做了什么事情 
> NumPy 的智能做法：把 vec 自动"复制"成3行，让它可以和 mat 的每一行相加

原始 mat:              原始 vec:
[ 0  1  2  3]         [100 200 300 400]
[ 4  5  6  7]
[ 8  9 10 11]

广播后的 vec (自动扩展):
[100 200 300 400]
[100 200 300 400]  ← 重复了3次，变成3行4列
[100 200 300 400]

然后逐元素相加:
[0+100, 1+200, 2+300, 3+400] = [100, 201, 302, 403]
[4+100, 5+200, 6+300, 7+400] = [104, 205, 306, 407]
[8+100, 9+200, 10+300, 11+400] = [108, 209, 310, 411]

"""

# 标量广播
print("所有元素乘以 2:\n", mat * 2)

# 列向量 (3,1) 与行向量 (1,4) 广播成 (3,4)
col = np.array([1, 2, 3]).reshape(3, 1)
row = np.array([10, 20, 30, 40])
print("\n列向量:\n", col)
print("行向量:", row)
print("相加结果:\n", col + row)

"""
第一步：扩展 col（从 3×1 扩展到 3×4）
原始 col:          扩展后 col:
[1]                [1, 1, 1, 1]   ← 把唯一的值复制4份
[2]      ——→       [2, 2, 2, 2]   ← 把唯一的值复制4份
[3]                [3, 3, 3, 3]   ← 把唯一的值复制4份


第二步：扩展 row（从 4 扩展到 3×4）
原始 row:          扩展后 row:
[10,20,30,40]      [10, 20, 30, 40]
         ——→       [10, 20, 30, 40]   ← 把这一行复制3份
                   [10, 20, 30, 40]

                   
第三步：两个扩展后的数组逐元素相加
扩展后的 col:       扩展后的 row:        结果:
[1, 1, 1, 1]      [10,20,30,40]      [11,21,31,41]
[2, 2, 2, 2]   +  [10,20,30,40]   =  [12,22,32,42]
[3, 3, 3, 3]      [10,20,30,40]      [13,23,33,43]         

"""



"""
目的：理解不同形状数组如何自动扩展进行运算。

解释：当两个数组形状不匹配时，NumPy 会尝试“广播”较小的数组，使其形状与较大数组一致。

规则是：从尾部维度开始比较，维度相等或其中一个为 1 即可广播。

广播避免了显式复制数据，节省内存

"""