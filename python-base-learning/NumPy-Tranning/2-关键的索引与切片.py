import numpy as np

# 创建一个 3x4 的数组
arr = np.arange(12).reshape(3, 4)   # 0~11 重新形状为 3 行 4 列
print("原始数组:\n", arr)

# 取第 1 行第 2 列的元素 (索引从 0 开始)
print("元素 (1,2):", arr[1, 2])

# 切片：前两行，后三列
print("前两行，后三列:\n", arr[:2, 1:4])

# 修改切片的值 (会影响原数组)
arr[0, :] = 99   # 将第 0 行全部设为 99
print("修改后:\n", arr)

"""
解释：NumPy 的切片语法与 Python 列表完全一致（[start:stop:step]），
但可以同时在多个维度上用逗号分隔。切片返回的是原数组的视图（view），修改视图会改变原数组，这是高效的内存行为。
"""