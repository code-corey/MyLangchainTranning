import torch
import math

print("=" * 70)
print("对比：手动算导数 vs PyTorch自动求导")
print("任务：教会电脑 y = 3 * x")
print("=" * 70)

"""
也就是当我输入 一个x的时候 得到的结果是 3 * x
公式就是 ：y= w * x  
这个 w，我们当前并不知道是什么，所以要进行一次一次的猜测

"""

# ==================== 方法1：手动算导数 ====================
print("\n【方法1：手动算导数】")
print("-" * 50)

# 电脑随便猜一个数
w_manual = 12.0
print(f"初始猜测: w = {w_manual}")

# 我们给定一个训练数据，也就是样例输入：（x=2 时 y 应该是 6）
# 我们目前就是想得这样的一个固定的公式，看看 这里的 w 究竟是什么
x = 2.0
正确答案 = 6.0

# 训练10次
for i in range(1, 11):
    # 前向传播：计算猜测
    # 前向传播 = 把输入扔进模型，算出预测结果
    # 假设世界可以用 输出 = w × 输入
    猜测 = w_manual * x

    # 计算损失 (猜测 - 正确答案)的平方
    损失 = (猜测 - 正确答案) ** 2

    # 【手动计算导数】
    # 公式：损失 = (w*x - 正确)²
    # 导数 = 2 * (w*x - 正确) * x
    导数 = 2 * (猜测 - 正确答案) * x
    """
    求导数的目的是：告诉电脑应该往哪个方向调整 w，以及调整多少
    
    公式为：导数 = 2 * (猜测 - 正确答案) * x
    
    如果当前我们这个 w值猜小了，那么 猜测-正确答案<0 , 就是负数 (也就是下坡了)，我们需要做的是 增加w
    
    如果当前我们这个 w值猜大了，那么 猜测-正确答案>0 , 就是正数 (也就是上坡了)，我们需要做的是 增加w

    所以，我们求导数，就是想知道我们下一步究竟往哪个方向走
    """

    """
    导数 = 损失的变化率
    具体说：导数 = 当 w 增加1时，损失会变化多少
    比如说：
    导数为 +8 ，也就是当w增加时，损失增加了8，变得更差了，推导出，我们需要 减少w 
    导数为 -8 ，也就是当w减少时，损失减少了8，变得更好了，推导出，我们需要 增加w
    
    所以，我们发现了一个规律：行动方向 = - 导数方向
    
    接下来我们需要控制一下，每次的步伐究竟是多大，如果过大的话，可能就像摇摆的时钟一样，到不了终点
    
    最终的公式为：
    w_new = w - 学习率(步子) × 导数
    """


    # 更新参数
    # 这里的0.1 就是步子
    #
    w_manual = w_manual - 0.1 * 导数

    print(f"第{i:2d}次: w = {w_manual:.4f}, 损失 = {损失:.4f}, 手动算的导数 = {导数:.2f}")

print(f"\n手动方法结果：w = {w_manual:.4f}")

# ==================== 方法2：PyTorch自动求导 ====================
print("\n【方法2：PyTorch自动求导】")
print("-" * 50)

# 电脑随便猜一个数（注意requires_grad=True）
w_auto = torch.tensor([2.0], requires_grad=True)
print(f"初始猜测: w = {w_auto.item()}")

# 同样的训练数据
x = torch.tensor([2.0])
正确答案 = torch.tensor([6.0])

# 训练10次
for i in range(1, 11):
    # 前向传播：计算猜测
    猜测 = w_auto * x

    # 计算损失
    损失 = (猜测 - 正确答案) ** 2

    # 【自动求导】PyTorch自动算导数！
    损失.backward()  # ← 这一行代替了手动计算

    # 查看PyTorch算出的导数
    pytorch_导数 = w_auto.grad.item()

    # 更新参数
    with torch.no_grad():
        w_auto -= 0.1 * w_auto.grad
        w_auto.grad.zero_()  # 清空梯度

    print(f"第{i:2d}次: w = {w_auto.item():.4f}, 损失 = {损失.item():.4f}, PyTorch自动算的导数 = {pytorch_导数:.2f}")

print(f"\nPyTorch自动方法结果：w = {w_auto.item():.4f}")

# ==================== 总结对比 ====================
print("\n" + "=" * 70)
print("【总结对比】")
print("=" * 70)
print("手动方法：")
print("  - 需要自己推导导数公式：导数 = 2 * (猜测 - 正确) * x")
print("  - 如果公式复杂，很容易算错")
print("  - 神经网络有100万参数时，根本算不了")
print("\nPyTorch自动求导：")
print("  - 只需写 loss.backward()，自动算所有导数")
print("  - 永远正确，不会算错")
print("  - 不管模型多复杂都能算")
