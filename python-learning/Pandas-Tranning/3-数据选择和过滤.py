import pandas as pd

# 创建示例数据
df = pd.DataFrame({
    '姓名': ['张三', '李四', '王五', '赵六', '小明', '小红'],
    '年龄': [25, 30, 28, 35, 22, 27],
    '城市': ['北京', '上海', '北京', '深圳', '上海', '北京'],
    '工资': [8000, 12000, 9500, 15000, 6000, 8500],
    '部门': ['销售', '技术', '销售', '管理', '技术', '销售']
})

print("原始数据:")
print(df)

# 选择单列（得到Series）
print("\n选择'姓名'列:")
print(df['姓名'])

# 选择多列（得到DataFrame）
print("\n选择'姓名'和'工资'列:")
print(df[['姓名', '工资']])

# 选择行（用iloc按位置）
print("\n前3行（iloc）:")
print(df.iloc[:3])

# 选择行（用loc按标签）
print("\n第2到第4行（loc）:")
print(df.loc[1:3])

# 条件筛选
print("\n工资大于9000的人:")
print(df[df['工资'] > 9000])

# 多条件筛选（& 表示且，| 表示或）
print("\n工资大于8000且城市是北京的人:")
print(df[(df['工资'] > 8000) & (df['城市'] == '北京')])

# 使用isin筛选
print("\n城市是北京或上海的人:")
print(df[df['城市'].isin(['北京', '上海'])])


""" 
解释：df['列名']选择列；df[条件]筛选行；iloc用位置索引；loc用标签索引；&和|组合条件。
""" 